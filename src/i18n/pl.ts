/** Polish plural: 1 bieg, 2–4 biegi (but 12–14 biegów), 5+ biegów. */
function plural(n: number, one: string, few: string, many: string): string {
  if (n === 1) return one;
  const last = n % 10;
  const lastTwo = n % 100;
  return last >= 2 && last <= 4 && (lastTwo < 12 || lastTwo > 14) ? few : many;
}

